import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { formatCommitmentPrefix as builtFormatCommitmentPrefix } from '@veripact/core';
import {
  canonicalizeJson,
  COMMITMENT_LENGTH,
  COMMITMENT_PREFIX,
  computeCommitment,
  deriveEd25519KeyPairFromSeed,
  evaluateContestedDispute,
  formatCommitmentPrefix,
  generateEd25519KeyPair,
  sha256Hex,
  signCanonicalPayload,
  verifyCanonicalPayload,
  type MandateSpec,
  type SignedReceipt,
} from '../src/index';

const VALID_HEX = '9f86d081884c7d659a2feaa0c55ad015a3bf4f1b2b0b822cd15d6c15b0f00a08';

// Deterministic TEST-ONLY seeds (generated by .tools/gen_mandate.js; never live keys).
const BUYER_SEED = '11'.repeat(32);
const WITNESS_SEED = '22'.repeat(32);
const REF_BUYER_SEED = 'aa'.repeat(32);
const REF_WITNESS_SEED = 'bb'.repeat(32);
const BUYER_PUB = 'd04ab232742bb4ab3a1368bd4615e4e6d0224ab71a016baf8520a332c9778737';
const REF_BUYER_PUB = 'e734ea6c2b6257de72355e472aa05a4c487e6b463c029ed306df2f01b5636b58';
const REF_WITNESS_PUB = '7d59c5623dd40a74aa4d5a32ac645d3b3f95daeae4c22be25476dd6a486f7382';

function signed(payload: unknown, seedHex: string): SignedReceipt {
  const kp = deriveEd25519KeyPairFromSeed(seedHex);
  return {
    payload,
    signatureHex: signCanonicalPayload(payload, kp.privateKeyHex),
    publicKeyHex: kp.publicKeyHex,
  };
}

describe('@veripact/core', () => {
  it('formats a 68-char VP1 commitment from valid sha256 hex', () => {
    const commitment = formatCommitmentPrefix(VALID_HEX);
    expect(commitment).toBe(`${COMMITMENT_PREFIX}${VALID_HEX}`);
    expect(commitment).toHaveLength(COMMITMENT_LENGTH);
  });

  it('rejects short, long, non-hex, and uppercase digests', () => {
    expect(() => formatCommitmentPrefix('abc')).toThrow(/invalid sha256/);
    expect(() => formatCommitmentPrefix(`${VALID_HEX}00`)).toThrow(/invalid sha256/);
    expect(() => formatCommitmentPrefix(`z${VALID_HEX.slice(1)}`)).toThrow(/invalid sha256/);
    expect(() => formatCommitmentPrefix(VALID_HEX.toUpperCase())).toThrow(/invalid sha256/);
  });

  it('accepts a well-formed MandateSpec', () => {
    const mandate: MandateSpec = {
      mandateId: 'mnd_test_001',
      createdAtUtc: '2026-11-01T06:30:00.000Z',
      buyerId: 'buyer_sandbox_01',
      itemQuery: '27-inch 4K IPS Monitor',
      constraints: {
        requiredCondition: 'NEW',
        maxAllInPriceUsd: 320,
        minReturnWindowDays: 30,
        maxRestockingFeePct: 0,
      },
      buyerPublicKeyHex: 'd75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a',
      buyerSignatureHex: '92a4c8',
    };
    expect(mandate.constraints.maxAllInPriceUsd).toBe(320);
  });

  it('resolves the built package by workspace name', () => {
    expect(builtFormatCommitmentPrefix('0'.repeat(64))).toBe(`VP1:${'0'.repeat(64)}`);
  });

  it('canonicalizes objects with lexicographic key order, recursively', () => {
    expect(canonicalizeJson({ b: 1, a: 2 })).toBe('{"a":2,"b":1}');
    expect(canonicalizeJson({ z: { d: 4, c: 3 }, a: [3, 2, 1] })).toBe(
      '{"a":[3,2,1],"z":{"c":3,"d":4}}',
    );
    expect(canonicalizeJson({ 2: 'x', 10: 'y', b: 'z' })).toBe('{"10":"y","2":"x","b":"z"}');
    expect(canonicalizeJson({})).toBe('{}');
    expect(canonicalizeJson([])).toBe('[]');
  });

  it('drops undefined members and nulls them in arrays', () => {
    expect(canonicalizeJson({ a: 1, b: undefined })).toBe('{"a":1}');
    expect(canonicalizeJson([1, undefined, 'x'])).toBe('[1,null,"x"]');
  });

  it('escapes strings per RFC 8785 and passes unicode through', () => {
    expect(canonicalizeJson({ q: 'a"b\\c\x01' })).toBe(String.raw`{"q":"a\"b\\c\u0001"}`);
    expect(canonicalizeJson({ s: 'é☃' })).toBe('{"s":"é☃"}');
  });

  it('formats numbers per ECMAScript with -0 as 0', () => {
    expect(canonicalizeJson({ n: -0 })).toBe('{"n":0}');
    expect(canonicalizeJson({ n: 1.5 })).toBe('{"n":1.5}');
    expect(canonicalizeJson({ n: Number.NaN })).toBe('{"n":null}');
    expect(canonicalizeJson({ n: 1e21 })).toBe('{"n":1e+21}');
  });

  it('throws on non-data top levels', () => {
    expect(() => canonicalizeJson(undefined)).toThrow(TypeError);
  });

  it('hashes sha256 to known vectors', () => {
    expect(sha256Hex('abc')).toBe('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
    expect(sha256Hex(Buffer.from('abc', 'utf8'))).toBe(sha256Hex('abc'));
  });

  it('computes deterministic 68-char VP1 commitments', () => {
    const a = computeCommitment({ b: 2, a: 1 });
    const b = computeCommitment({ a: 1, b: 2 });
    expect(a).toBe(b);
    expect(a).toHaveLength(COMMITMENT_LENGTH);
    expect(a.startsWith(COMMITMENT_PREFIX)).toBe(true);
    expect(a).toBe(`${COMMITMENT_PREFIX}${sha256Hex(canonicalizeJson({ a: 1, b: 2 }))}`);
  });

  it('generates well-formed random keypairs', () => {
    const kp = generateEd25519KeyPair();
    expect(kp.publicKeyHex).toMatch(/^[0-9a-f]{64}$/);
    expect(kp.privateKeyHex).toMatch(/^[0-9a-f]{64}$/);
    expect(kp.keyFingerprint).toBe(sha256Hex(Buffer.from(kp.publicKeyHex, 'hex')).slice(0, 16));
    expect(generateEd25519KeyPair().publicKeyHex).not.toBe(kp.publicKeyHex);
  });

  it('derives deterministic keypairs from fixed test seeds', () => {
    const buyer = deriveEd25519KeyPairFromSeed(BUYER_SEED);
    expect(buyer.publicKeyHex).toBe(BUYER_PUB);
    expect(buyer.privateKeyHex).toBe(BUYER_SEED);
    expect(buyer.keyFingerprint).toBe('10ba682c8ad13513');
    expect(deriveEd25519KeyPairFromSeed(BUYER_SEED).publicKeyHex).toBe(BUYER_PUB);
    expect(deriveEd25519KeyPairFromSeed(REF_BUYER_SEED).publicKeyHex).toBe(REF_BUYER_PUB);
    expect(deriveEd25519KeyPairFromSeed(REF_WITNESS_SEED).publicKeyHex).toBe(REF_WITNESS_PUB);
    expect(() => deriveEd25519KeyPairFromSeed('abc')).toThrow(/64 lowercase hex/);
  });

  it('signs and verifies canonical payloads, rejecting tampering', () => {
    const buyer = deriveEd25519KeyPairFromSeed(BUYER_SEED);
    const witness = deriveEd25519KeyPairFromSeed(WITNESS_SEED);
    const payload = { terms: '30-day free returns', price: 279 };
    const sig = signCanonicalPayload(payload, buyer.privateKeyHex);
    expect(sig).toMatch(/^[0-9a-f]{128}$/);
    expect(verifyCanonicalPayload(payload, sig, buyer.publicKeyHex)).toBe(true);
    expect(
      verifyCanonicalPayload({ terms: '14-day returns', price: 279 }, sig, buyer.publicKeyHex),
    ).toBe(false);
    expect(verifyCanonicalPayload(payload, sig, witness.publicKeyHex)).toBe(false);
    expect(verifyCanonicalPayload(payload, '0'.repeat(127), buyer.publicKeyHex)).toBe(false);
    expect(verifyCanonicalPayload(payload, 'x'.repeat(128), buyer.publicKeyHex)).toBe(false);
    expect(verifyCanonicalPayload(payload, sig.toUpperCase(), buyer.publicKeyHex)).toBe(false);
    expect(verifyCanonicalPayload(payload, sig, 'not-hex')).toBe(false);
    expect(() => signCanonicalPayload(payload, 'bad')).toThrow(/64 lowercase hex/);
  });

  it('verifies the live .veripact/mandates.json signature and rejects $0.01 drift', () => {
    const root = process.cwd(); // vitest runs from the repo root
    const file = JSON.parse(readFileSync(join(root, '.veripact', 'mandates.json'), 'utf8')) as {
      mandate_hash: string;
      buyer_signature_hex: string;
      buyer_public_key_hex: string;
      constraints: { max_all_in_price_usd: number };
    } & Record<string, unknown>;
    const { mandate_hash: mandateHash, buyer_signature_hex: signature, ...signPayload } = file;
    expect(mandateHash).toBe(sha256Hex(canonicalizeJson(signPayload)));
    expect(verifyCanonicalPayload(signPayload, signature, file.buyer_public_key_hex)).toBe(true);
    const mutatedPayload = JSON.parse(JSON.stringify(signPayload)) as typeof signPayload;
    mutatedPayload.constraints.max_all_in_price_usd += 0.01;
    expect(verifyCanonicalPayload(mutatedPayload, signature, file.buyer_public_key_hex)).toBe(false);
  });

  it('referee detects buyer forgery despite a valid self-signature (Case B)', () => {
    const witnessed = { terms: '30-day free returns', price: 279 };
    const forged = { terms: '60-day free returns + $50 rebate', price: 279 };
    const result = evaluateContestedDispute({
      paypalOrderCustomId: computeCommitment(witnessed),
      witnessReceipt: signed(witnessed, REF_WITNESS_SEED),
      buyerClaimReceipt: signed(forged, REF_BUYER_SEED),
      sellerCounterClaimReceipt: signed(witnessed, REF_WITNESS_SEED),
    });
    expect(result.verdict).toBe('BUYER_FORGERY_DETECTED');
    expect(result.buyerSignatureValid).toBe(true);
    expect(result.buyerHashMatch).toBe(false);
    expect(result.anchorTrusted).toBe(true);
  });

  it('referee confirms merchant drift against a matching buyer receipt (Case A)', () => {
    const witnessed = { terms: '30-day free returns', price: 279 };
    const drifted = { terms: '14-day returns / 25% fee', price: 279 };
    const result = evaluateContestedDispute({
      paypalOrderCustomId: computeCommitment(witnessed),
      witnessReceipt: signed(witnessed, REF_WITNESS_SEED),
      buyerClaimReceipt: signed(witnessed, REF_BUYER_SEED),
      sellerCounterClaimReceipt: signed(drifted, REF_WITNESS_SEED),
    });
    expect(result.verdict).toBe('MERCHANT_DRIFT_CONFIRMED');
    expect(result.buyerHashMatch).toBe(true);
    expect(result.sellerHashMatch).toBe(false);
    expect(result.anchorTrusted).toBe(true);
  });

  it('referee honors terms when all receipts match (happy path)', () => {
    const witnessed = { terms: '30-day free returns', price: 279 };
    const result = evaluateContestedDispute({
      paypalOrderCustomId: computeCommitment(witnessed),
      witnessReceipt: signed(witnessed, REF_WITNESS_SEED),
      buyerClaimReceipt: signed(witnessed, REF_BUYER_SEED),
      sellerCounterClaimReceipt: signed(witnessed, REF_WITNESS_SEED),
    });
    expect(result.verdict).toBe('TERMS_HONORED');
    expect(result.anchorTrusted).toBe(true);
  });

  it('referee stays deterministic with an untrusted witness anchor', () => {
    const witnessed = { terms: '30-day free returns', price: 279 };
    const drifted = { terms: '14-day returns / 25% fee', price: 279 };
    const result = evaluateContestedDispute({
      paypalOrderCustomId: computeCommitment(witnessed),
      witnessReceipt: {
        payload: witnessed,
        // Wrong-signer anchor: buyer signature presented under the witness key.
        signatureHex: signCanonicalPayload(
          witnessed,
          deriveEd25519KeyPairFromSeed(REF_BUYER_SEED).privateKeyHex,
        ),
        publicKeyHex: REF_WITNESS_PUB,
      },
      buyerClaimReceipt: signed(witnessed, REF_BUYER_SEED),
      sellerCounterClaimReceipt: signed(drifted, REF_WITNESS_SEED),
    });
    expect(result.witnessSignatureValid).toBe(false);
    expect(result.witnessHashMatch).toBe(true);
    expect(result.anchorTrusted).toBe(false);
    expect(result.verdict).toBe('MERCHANT_DRIFT_CONFIRMED');
    expect(result.reason).toContain('NOT verified');
  });
});
